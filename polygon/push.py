#!/usr/bin/env python3
"""Create/update ICPC HUE problems in Polygon through the Polygon API.

    python3 polygon/push.py polygon/level0-sheet1            # all problems in a sheet
    python3 polygon/push.py polygon/level0-sheet1/A-say-hello

Each problem folder holds: problem.json (name, title, limits, checker, sample
test indices), statement.json (legend, input, output, notes), validator.cpp,
solution.cpp (main correct solution), wrong-*.cpp (expected to fail), and
tests/NN.txt (inputs; answers are generated by Polygon from the main solution).

Credentials come from the environment or next-app/.env.local:
    POLYGON_API_KEY=...      POLYGON_API_SECRET=...
(Polygon -> Settings -> API keys). They are never printed.

Re-running is safe: an existing problem with the same name is updated.
Problem ids are stored in <sheet>/polygon-ids.json.
"""
import hashlib
import json
import os
import random
import string
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

API = 'https://polygon.codeforces.com/api/'
ROOT = Path(__file__).resolve().parent


def load_credentials():
    key, secret = os.environ.get('POLYGON_API_KEY'), os.environ.get('POLYGON_API_SECRET')
    env = ROOT.parent / 'next-app' / '.env.local'
    if (not key or not secret) and env.exists():
        for line in env.read_text().splitlines():
            if '=' not in line or line.lstrip().startswith('#'):
                continue
            k, v = line.split('=', 1)
            v = v.strip().strip('"\'')
            if k.strip() == 'POLYGON_API_KEY' and not key:
                key = v
            if k.strip() == 'POLYGON_API_SECRET' and not secret:
                secret = v
    if not key or not secret:
        sys.exit('Missing POLYGON_API_KEY / POLYGON_API_SECRET (add them to next-app/.env.local).')
    return key, secret


KEY, SECRET = load_credentials()


def call(method, **params):
    """Signed POST to the Polygon API; returns `result` or exits with the error."""
    params = {k: ('true' if v is True else 'false' if v is False else str(v)) for k, v in params.items()}
    params['apiKey'] = KEY
    params['time'] = str(int(time.time()))
    rand = ''.join(random.choice(string.ascii_lowercase + string.digits) for _ in range(6))
    signed = '&'.join(f'{k}={v}' for k, v in sorted(params.items()))
    params['apiSig'] = rand + hashlib.sha512(f'{rand}/{method}?{signed}#{SECRET}'.encode('utf-8')).hexdigest()
    req = urllib.request.Request(API + method, data=urllib.parse.urlencode(params).encode('utf-8'), method='POST')
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            body = json.loads(r.read().decode('utf-8'))
    except urllib.error.HTTPError as e:
        body = json.loads(e.read().decode('utf-8') or '{}')
    if body.get('status') != 'OK':
        sys.exit(f'{method} failed: {body.get("comment")}')
    return body.get('result')


def push_problem(folder: Path, ids: dict):
    meta = json.loads((folder / 'problem.json').read_text())
    st = json.loads((folder / 'statement.json').read_text())
    name = meta['name']

    pid = ids.get(name)
    if not pid:
        existing = [p for p in call('problems.list', name=name) if p.get('name') == name and not p.get('deleted')]
        pid = existing[0]['id'] if existing else call('problem.create', name=name)['id']
        ids[name] = pid
    print(f'{name}: problem {pid}')

    call('problem.updateInfo', problemId=pid, inputFile='stdin', outputFile='stdout', interactive=False,
         timeLimit=meta['timeLimit'], memoryLimit=meta['memoryLimit'])
    call('problem.saveStatement', problemId=pid, lang='english', encoding='UTF-8', name=meta['title'],
         legend=st['legend'], input=st['input'], output=st['output'], notes=st.get('notes', ''))

    call('problem.saveFile', problemId=pid, type='source', name='validator.cpp',
         file=(folder / 'validator.cpp').read_text(), sourceType='cpp.g++17')
    call('problem.setValidator', problemId=pid, validator='validator.cpp')
    call('problem.setChecker', problemId=pid, checker=meta['checker'])

    call('problem.saveSolution', problemId=pid, name='solution.cpp', file=(folder / 'solution.cpp').read_text(),
         sourceType='cpp.g++17', tag='MA')
    for wrong in sorted(folder.glob('wrong-*.cpp')):
        call('problem.saveSolution', problemId=pid, name=wrong.name, file=wrong.read_text(),
             sourceType='cpp.g++17', tag='WA')

    tests = sorted((folder / 'tests').glob('*.txt'))
    for i, t in enumerate(tests, 1):
        call('problem.saveTest', problemId=pid, testset='tests', testIndex=i, testInput=t.read_text(),
             testUseInStatements=i in meta.get('samples', [1]))
    print(f'  statement, validator, checker {meta["checker"]}, {1 + len(list(folder.glob("wrong-*.cpp")))} solutions, {len(tests)} tests')

    commit = call('problem.commitChanges', problemId=pid, minorChanges=False, message='ICPC HUE upload')
    print(f'  committed: {commit.get("message") if isinstance(commit, dict) else commit}')
    call('problem.buildPackage', problemId=pid, full=True, verify=True)
    print('  package build started (full + verify: all solutions run on all tests)')


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    target = Path(sys.argv[1]).resolve()
    sheet = target if (target / 'problem.json').exists() is False else target.parent
    folders = [target] if (target / 'problem.json').exists() else sorted(p for p in target.iterdir() if (p / 'problem.json').exists())
    ids_file = sheet / 'polygon-ids.json'
    ids = json.loads(ids_file.read_text()) if ids_file.exists() else {}
    for f in folders:
        push_problem(f, ids)
        ids_file.write_text(json.dumps(ids, indent=2) + '\n')
    print(f'\nDone. Ids in {ids_file}. Check each problem in Polygon -> Packages once the build finishes.')


if __name__ == '__main__':
    main()
